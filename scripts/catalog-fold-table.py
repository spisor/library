"""Writes runtime/src/catalog_fold_table.c: what one code point folds to, and each combining class.

A catalog refuses two file keys of one version that name one file on a file system that ignores case
and normalization, as Windows and macOS do. forebay/host compared key.normalize("NFC").toLowerCase();
the C reader compares the canonical decomposition of the lowercased decomposition, which answers the
same for every pair forebay/host's tests and the fixtures name. Hangul syllables decompose by formula
in the C code, so they are left out of the table.

Run with any Python 3; the table follows that Python's Unicode version, printed into the file.
"""

import sys
import unicodedata
from pathlib import Path

HANGUL_FIRST = 0xAC00
HANGUL_LAST = 0xD7A3
TARGET = Path(__file__).resolve().parent.parent / "runtime" / "src" / "catalog_fold_table.c"


def code_points():
    for code_point in range(0x110000):
        if 0xD800 <= code_point <= 0xDFFF or HANGUL_FIRST <= code_point <= HANGUL_LAST:
            continue
        yield code_point


def folded(code_point):
    text = chr(code_point)
    return unicodedata.normalize("NFD", unicodedata.normalize("NFD", text).lower())


def fold_entries():
    for code_point in code_points():
        result = folded(code_point)
        if result != chr(code_point):
            yield code_point, [ord(character) for character in result]


def class_ranges():
    ranges = []
    for code_point in code_points():
        combining = unicodedata.combining(chr(code_point))
        if combining == 0:
            continue
        if ranges and ranges[-1][1] == code_point - 1 and ranges[-1][2] == combining:
            ranges[-1][1] = code_point
        else:
            ranges.append([code_point, code_point, combining])
    return ranges


def rows(values, per_line):
    for start in range(0, len(values), per_line):
        yield "    " + " ".join(values[start:start + per_line])


def render():
    entries = list(fold_entries())
    pool = []
    lines = [
        "/* Generated by scripts/catalog-fold-table.py from Unicode %s; do not edit. */" % unicodedata.unidata_version,
        "",
        '#include "catalog_fold_table.h"',
        "",
        "const runtime_catalog_fold_entry runtime_catalog_fold_entries[] = {",
    ]
    cells = []
    for code_point, mapped in entries:
        cells.append("{0x%X, %d, %d}," % (code_point, len(pool), len(mapped)))
        pool.extend(mapped)
    lines.extend(rows(cells, 6))
    lines.append("};")
    lines.append("")
    lines.append("const size_t runtime_catalog_fold_entry_count = sizeof runtime_catalog_fold_entries / sizeof runtime_catalog_fold_entries[0];")
    lines.append("")
    lines.append("const uint32_t runtime_catalog_fold_pool[] = {")
    lines.extend(rows(["0x%X," % value for value in pool], 12))
    lines.append("};")
    lines.append("")
    lines.append("const runtime_catalog_class_range runtime_catalog_class_ranges[] = {")
    lines.extend(rows(["{0x%X, 0x%X, %d}," % tuple(entry) for entry in class_ranges()], 5))
    lines.append("};")
    lines.append("")
    lines.append("const size_t runtime_catalog_class_range_count = sizeof runtime_catalog_class_ranges / sizeof runtime_catalog_class_ranges[0];")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    sys.stdout.write("wrote %s\n" % TARGET)
