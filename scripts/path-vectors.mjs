const vectors = {
  generator: `node ${process.version}`,
  join: joinCases.map((segments) => ({
    segments,
    posix: posix.join(...segments),
    win32: win32.join(...segments),
  })),
  absolute: absoluteCases.map((path) => ({
    path,
    posix: posix.isAbsolute(path),
    win32: win32.isAbsolute(path),
  })),
};

const output = join(dirname(fileURLToPath(import.meta.url)), "..", "test", "vectors", "path-join.json");
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `${JSON.stringify(vectors, null, 2)}\n`);
console.log(`wrote ${vectors.join.length} join and ${vectors.absolute.length} absolute vectors to ${output}`);
